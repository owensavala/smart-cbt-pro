/**
 * Tier 1: Feature Coverage - Requirement R3: Pembaruan Metadata Title (P2)
 * 
 * Authoritative Source: ORIGINAL_REQUEST.md § R3 & PROJECT.md § M2
 * Requirement:
 *   Perbarui title pada src/app/layout.tsx dari 'Create Next App' menjadi judul representatif
 *   seperti 'SmartCBT Pro - Platform Ujian Berbasis Komputer'.
 */

import { describe, it, expect, setTestTier } from '../helpers/test-harness';
import { readProjectFile } from '../helpers/opaque-inspect';

export async function runR3Tests() {
  setTestTier('Tier 1: R3 Metadata Title');

  await describe('R3.1 - Application Metadata and Document Header Compliance', async () => {
    await it('T1_R3_01_layout_metadata_title_is_smartcbt_pro: src/app/layout.tsx exports metadata title matching "SmartCBT Pro - Platform Ujian Berbasis Komputer"', async () => {
      const layoutContent = readProjectFile('src/app/layout.tsx');

      expect(layoutContent).toContain('SmartCBT Pro - Platform Ujian Berbasis Komputer');
    });

    await it('T1_R3_02_layout_metadata_title_not_create_next_app: src/app/layout.tsx title does not equal "Create Next App"', async () => {
      const layoutContent = readProjectFile('src/app/layout.tsx');

      expect(layoutContent).not.toContain('title: "Create Next App"');
      expect(layoutContent).not.toContain("title: 'Create Next App'");
    });

    await it('T1_R3_03_root_html_lang_attribute_is_id: Root <html> element declares lang="id" for Indonesian locale', async () => {
      const layoutContent = readProjectFile('src/app/layout.tsx');

      expect(layoutContent).toContain('lang="id"');
      expect(layoutContent).not.toContain('lang="en"');
    });

    await it('T1_R3_04_metadata_description_is_representative: Metadata description is updated from boilerplate', async () => {
      const layoutContent = readProjectFile('src/app/layout.tsx');

      expect(layoutContent).not.toContain('description: "Generated by create next app"');
      expect(layoutContent).not.toContain("description: 'Generated by create next app'");
    });

    await it('T1_R3_05_no_create_next_app_in_layout: Complete layout.tsx contains zero references to Create Next App', async () => {
      const layoutContent = readProjectFile('src/app/layout.tsx');

      const containsCreateNextApp = /create\s+next\s+app/i.test(layoutContent);
      expect(containsCreateNextApp).toBe(false);
    });
  });
}
